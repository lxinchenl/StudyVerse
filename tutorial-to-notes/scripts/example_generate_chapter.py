def sf(run, font='宋体', sz=Pt(12), b=False):
    run.font.name = 'Times New Roman'; run.font.size = sz; run.font.bold = b
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = parse_xml(f'<w:rFonts {nsdecls("w")} w:eastAsia="{font}"/>')
        rPr.insert(0, rFonts)
    else:
        rFonts.set(qn('w:eastAsia'), font)

def h1(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(6); p.paragraph_format.line_spacing = 1.5
    r = p.add_run(text); sf(r, '宋体', Pt(18), True)

